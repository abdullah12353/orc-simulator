// `npm run tone-bible:sync`: copies the tone bible (.scratch/orc-nonsense/tone-bible.md) into
// packages/content/src/tone-bible.ts, the narration system prompt's prefix (story 118). A content test
// fails when the two drift apart. A TS module, not a file read, so Deno bundles it into the functions.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const doc = readFileSync(join(root, '.scratch', 'orc-nonsense', 'tone-bible.md'), 'utf8').replace(/\r\n/g, '\n');
const out = `// GENERATED by \`npm run tone-bible:sync\` from .scratch/orc-nonsense/tone-bible.md. Don't edit by hand.
/** The tone bible, the cached prefix of every narration prompt (story 118). */
export const TONE_BIBLE = ${JSON.stringify(doc)};
`;
writeFileSync(join(root, 'packages', 'content', 'src', 'tone-bible.ts'), out);
console.log(`tone-bible.ts: ${doc.length} chars`);
